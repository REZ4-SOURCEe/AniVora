/* ============================================
   HELPER: دریافت همه اپیزودهای یک انیمه (از همه فصل‌ها)
============================================ */
export function getAllEpisodes(anime) {
  if (!anime) return [];
  if (anime.seasons && anime.seasons.length > 0) {
    let all = [];
    anime.seasons.forEach(s => {
      s.episodes.forEach(ep => {
        all.push({ ...ep, seasonNumber: s.seasonNumber });
      });
    });
    return all;
  }
  if (anime.episodes) return anime.episodes;
  return [];
}

/* ============================================
   HELPER: تعداد کل اپیزودهای یک انیمه
============================================ */
export function getTotalEpisodes(anime) {
  if (!anime) return 0;
  if (anime.seasons && anime.seasons.length > 0) {
    return anime.seasons.reduce((sum, s) => sum + s.episodes.length, 0);
  }
  return anime.episodes ? anime.episodes.length : 0;
}

/* ============================================
   HELPER: تعداد اپیزودهای پخش‌شده
============================================ */
export function getAiredEpisodes(anime) {
  if (!anime) return 0;
  if (anime.seasons && anime.seasons.length > 0) {
    return anime.seasons.reduce((sum, s) => sum + (s.episodesAired || s.episodes.length), 0);
  }
  return anime.episodesAired || (anime.episodes ? anime.episodes.length : 0);
}

